"""legal/*.md -> the in-app legal pages (const LEGAL in app/index.html) and public pages at the site root
(privacy.html, terms.html, licenses.html). The Markdown files are the single source; run after editing them
(build.sh runs it too).

Supports the small Markdown subset the legal files use: # / ## headings, paragraphs, "- " lists, **bold**,
4-space indented blocks (license texts), bare URLs and email addresses (made into links)."""
import html, json, re

DOCS = ["privacy", "terms", "licenses"]

def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"(https?://[^\s<)]+[^\s<).,;:])", r'<a href="\1" target="_blank" rel="noopener">\1</a>', t)
    t = re.sub(r"(?<![\w/.:-])([\w.+-]+@[\w-]+\.[\w.]+[a-z])", r'<a href="mailto:\1">\1</a>', t)
    return t

def md_to_html(md):
    out, para, items, pre = [], [], [], []
    def flush():
        if para: out.append("<p>" + inline(" ".join(para)) + "</p>"); para.clear()
        if items: out.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>"); items.clear()
        if pre:
            while pre and not pre[-1].strip(): pre.pop()
            out.append("<pre>" + html.escape("\n".join(pre)) + "</pre>"); pre.clear()
    title = ""
    for line in md.split("\n"):
        if line.startswith("    ") or (pre and not line.strip()):
            if para or items: flush()
            pre.append(line[4:]); continue
        if pre: flush()
        if not line.strip(): flush(); continue
        if line.startswith("# "): flush(); title = line[2:].strip(); continue
        if line.startswith("## "): flush(); out.append(f"<h3>{inline(line[3:].strip())}</h3>"); continue
        if line.startswith("- "):
            if para: flush()
            items.append(line[2:].strip()); continue
        if items and line.startswith("  "): items[-1] += " " + line.strip(); continue
        if items: flush()
        para.append(line.strip())
    flush()
    return title, "\n".join(out)

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{title}: Maroon, a free macro tracker for McMaster students.">
<style>
@font-face {{ font-family: "Figtree"; font-weight: 400; src: url("app/vendor/fonts/figtree-latin-400-normal.woff2") format("woff2"); }}
@font-face {{ font-family: "Figtree"; font-weight: 800; src: url("app/vendor/fonts/figtree-latin-800-normal.woff2") format("woff2"); }}
:root {{ --bg: #F6F4F8; --text: #1D1A21; --muted: #5E5866; --line: #DDD9E2; --surface: #FFFFFF; --accent: #7A003C; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg: #161318; --text: #F2EEF4; --muted: #B3ACBA; --line: #3A3340; --surface: #211C25; --accent: #FDBF57; }} }}
* {{ box-sizing: border-box; }}
body {{ margin: 0; background: var(--bg); color: var(--text); font: 16px/1.6 "Figtree", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }}
main {{ max-width: 720px; margin: 0 auto; padding: 32px 16px 64px; }}
h1 {{ font-size: 1.8rem; font-weight: 800; margin: 0 0 16px; color: var(--accent); line-height: 1.2; }}
h3 {{ font-size: 1.15rem; font-weight: 800; margin: 32px 0 8px; }}
a {{ color: var(--accent); overflow-wrap: anywhere; }}
pre {{ white-space: pre-wrap; font-size: 0.8rem; background: var(--surface); border: 1px solid var(--line); border-radius: 10px; padding: 12px; }}
nav {{ margin-bottom: 20px; font-size: 0.95rem; }}
</style>
</head>
<body>
<main>
<nav><a href="app/">← Back to Maroon</a></nav>
<h1>{title}</h1>
{body}
</main>
</body>
</html>
"""

if __name__ == "__main__":
    legal = {}
    for name in DOCS:
        title, body = md_to_html(open(f"legal/{name}.md", encoding="utf-8").read())
        legal[name] = {"title": title, "html": body}
        open(f"{name}.html", "w", encoding="utf-8").write(PAGE.format(title=html.escape(title), body=body))
    p = "app/index.html"
    s = open(p, encoding="utf-8").read()
    block = "/* LEGAL:START (generated by scripts/build_legal.py from legal/*.md; don't edit here) */\nconst LEGAL = " + \
        json.dumps(legal, ensure_ascii=False).replace("</", "<\\/") + ";\n/* LEGAL:END */"
    s2, n = re.subn(r"/\* LEGAL:START.*?/\* LEGAL:END \*/", lambda m: block, s, flags=re.S)
    if n != 1: raise SystemExit("LEGAL:START/END markers not found in app/index.html")
    if s2 != s: open(p, "w", encoding="utf-8").write(s2)
    print("legal pages built:", ", ".join(DOCS))
